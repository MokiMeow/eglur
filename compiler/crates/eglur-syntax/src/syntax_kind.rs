use crate::TokenKind;

macro_rules! define_syntax_kinds {
    ($($kind:ident),+ $(,)?) => {
        /// Token and node kinds in the lossless Eglur syntax tree.
        #[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
        #[repr(u16)]
        pub enum SyntaxKind {
            $($kind),+
        }

        pub(crate) const ALL_SYNTAX_KINDS: &[SyntaxKind] = &[
            $(SyntaxKind::$kind),+
        ];
    };
}

