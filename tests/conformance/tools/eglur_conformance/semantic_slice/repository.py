"""Repository adapter for the first semantic fixture corpus."""

import os
import tempfile
from pathlib import Path

from eglur_conformance.artifact_content import (
    canonical_digest,
    raw_artifact_digest,
)
from eglur_conformance.semantic_slice import codec, model, projection
from eglur_conformance.suite import repository as suite_repository

SELECTION_PATH = Path("tests/semantic/core-v1.selection.yaml")
CORPUS_PATH = Path("tests/semantic/core-v1.expectations.json")


def _resolved_repository_root(repo_root: Path) -> Path:
    if not isinstance(repo_root, Path):
        raise TypeError("repository root must be a Path")
    resolved = repo_root.resolve(strict=True)
    if not resolved.is_dir():
        raise ValueError(f"repository root is not a directory: {repo_root}")
    return resolved


def _input_digest(
    conformance: suite_repository.ConformanceInputs,
    selection_bytes: bytes,
) -> str:
    return canonical_digest(
        {
            "conformance_bundle": conformance.content_digest,
            "fixture_selection": raw_artifact_digest(selection_bytes),
        }
    )


def build_corpus(repo_root: Path) -> model.SemanticFixtureCorpus:
    """Build the exact first semantic corpus from authoritative inputs.

    Parameters
    ----------
    repo_root : pathlib.Path
        Git worktree root.

    Returns
    -------
    model.SemanticFixtureCorpus
        Deterministic selected source and expectation projection.

    Raises
    ------
    TypeError
        ``repo_root`` or an authored field has the wrong type.
    ValueError
        The selection, suite bundle, or selected fixture violates its contract.
    OSError
        A required repository artifact cannot be read.
    UnicodeDecodeError
        An authoritative artifact is not valid UTF-8.
    yaml.YAMLError
        An authoritative YAML artifact is malformed.
    """
    root = _resolved_repository_root(repo_root)
    conformance = suite_repository.load_conformance_inputs(root)
    selection_bytes = (root / SELECTION_PATH).read_bytes()
    selection = codec.decode_selection_bytes(selection_bytes)
    if len(selection.identities) != model.CORE_V1_FIXTURE_COUNT:
        raise ValueError(
            "core-v1 fixture selection must contain exactly "
            f"{model.CORE_V1_FIXTURE_COUNT} identities, "
            f"found {len(selection.identities)}"
        )
    return projection.project_corpus(
        conformance.bundle,
        selection,
        _input_digest(conformance, selection_bytes),
    )


def generated_corpus_bytes(repo_root: Path) -> bytes:
    """Return exact generated bytes for one repository checkout.

    Parameters
    ----------
    repo_root : pathlib.Path
        Git worktree root.

    Returns
    -------
    bytes
        Deterministically encoded semantic fixture corpus.
    """
    return codec.encode_corpus(build_corpus(repo_root))


def corpus_is_current(repo_root: Path) -> bool:
    """Return whether the checked-in corpus equals exact regeneration.

    Parameters
    ----------
    repo_root : pathlib.Path
        Git worktree root.

    Returns
    -------
    bool
        True only when the generated artifact exists and is byte-exact.
    """
    root = _resolved_repository_root(repo_root)
    try:
        current = (root / CORPUS_PATH).read_bytes()
    except FileNotFoundError:
        return False
    return current == generated_corpus_bytes(root)


def write_corpus(repo_root: Path) -> None:
    """Atomically replace the checked-in corpus with exact regeneration.

    Parameters
    ----------
    repo_root : pathlib.Path
        Git worktree root.
    """
    root = _resolved_repository_root(repo_root)
    output_path = root / CORPUS_PATH
    output_path.parent.mkdir(parents=True, exist_ok=True)
    content = generated_corpus_bytes(root)
    descriptor, temporary_name = tempfile.mkstemp(
        dir=output_path.parent,
        prefix=f".{output_path.name}.",
        suffix=".tmp",
    )
    temporary_path = Path(temporary_name)
    try:
        os.fchmod(descriptor, 0o644)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary_path, output_path)
    finally:
        try:
            os.close(descriptor)
        except OSError:
            pass
        temporary_path.unlink(missing_ok=True)
